// Auto-generates the next period's draft rota at T-19 (19 days before the
// next period start — see lib/rota-period-dates.js), so a head_nurse no
// longer has to click "Generate." Runs the exact same generateSchedule()
// engine the Rota page's manual "Generate" button uses (ported to plain JS —
// see nurse-api/lib/auto-schedule.generated.js and
// nurse-api/scripts/build-auto-schedule.js), and the same pre-flight/write
// sequence handleGenerate()/handleGenerateFacilityWide() do in rota.tsx,
// just run server-side against the DB directly instead of via the browser +
// HTTP API (no req.user for a cron tick — see routes/shift-assignments.js's
// capability rewrite for why manual generation now requires admin).
const cron = require("node-cron");
const pool = require("../db");
const { forEachHospital } = require("../lib/tenant-context");
const { persistRotaDraft } = require("../lib/persist-rota-draft");
const { activeRoleGroups, roleGroupResolver } = require("../lib/role-groups");
const { createSchedulingConfigurationService } = require("../lib/scheduling-configuration-service");
const configuredScheduling = createSchedulingConfigurationService(pool);
const { getWindowForPeriod, getUnitPeriod } = require("../lib/rota-period-dates");
const {
  generateSchedule,
  parseWards,
  summariseViolations,
} = require("../lib/auto-schedule.generated.js");
const { sendMail, portalUrl } = require("../lib/mailer");
const { isRotaJobPaused } = require("../lib/rota-job-pause");

function fmtPeriodDate(d) {
  return d
    ? new Date(String(d).slice(0, 10) + "T00:00:00").toLocaleDateString("en-GB", {
        day: "numeric",
        month: "short",
        year: "numeric",
      })
    : "";
}

// Same worst-case-per-ward/shift/role collapse the manual "Generate" button's
// toast uses (summariseViolations, shared via auto-schedule.ts) — so the
// email/audit log and the manual-generate toast always report identical
// numbers from identical logic, never two independently-drifting summaries.
function violationLines(violations) {
  return summariseViolations(violations).map(
    (v) =>
      `${v.ward} — ${v.shift === "M" ? "Morning" : "Night"} ${v.role}: need ${v.required}, have ${v.actual}`,
  );
}

const EMAIL_COPY = {
  rota_autogenerated: (facility, unitLabel, periodStart, violations) => ({
    subject: violations?.length
      ? `Draft rota generated — ${unitLabel} (staffing shortfall)`
      : `Draft rota generated — ${unitLabel}`,
    bodyHtml: `<p>The draft rota for <strong>${unitLabel}</strong> · ${facility} (period starting ${fmtPeriodDate(periodStart)}) has been automatically generated and is ready for review.</p>
<p>Head nurses: please review the draft and submit it for approval, or request edit access from the Rota page first if changes are needed before submitting.</p>${
      violations?.length
        ? `<p><strong>Ward minimums could not be fully met with the current staff:</strong></p>
<ul>${violationLines(violations)
            .map((l) => `<li>${l}</li>`)
            .join("")}</ul>`
        : ""
    }`,
    ctaPath: "/rota",
  }),
};

// Distinct from AUTO_END_LOCK_KEY (729312), AUTO_DECLINE_LOCK_KEY (729313),
// AUTO_EXPIRE_LOCUM_LOCK_KEY (729314) — see jobs/auto-end-shifts.js for why
// the lock exists.
const AUTO_GENERATE_LOCK_KEY = 729315;
const DRY_RUN = process.env.DRY_RUN_ROTA_JOBS === "true";

function ymd(d) {
  return `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, "0")}-${String(d.getDate()).padStart(2, "0")}`;
}
function addDays(dateStr, n) {
  const d = new Date(dateStr + "T00:00:00");
  d.setDate(d.getDate() + n);
  return ymd(d);
}
function daysBetween(fromStr, toStr) {
  return Math.round(
    (new Date(toStr + "T00:00:00").getTime() - new Date(fromStr + "T00:00:00").getTime()) /
      (24 * 60 * 60 * 1000),
  );
}

async function autoGenerateRota(opts = {}) {
  if (await isRotaJobPaused("auto_generate")) return;
  const lockClient = await pool.connect();
  try {
    const { rows } = await lockClient.query("SELECT pg_try_advisory_lock($1) AS locked", [
      AUTO_GENERATE_LOCK_KEY,
    ]);
    if (!rows[0].locked) return;
    await runAutoGenerate(opts);
  } catch (err) {
    console.error("[auto-generate-rota] Error:", err.message);
  } finally {
    await lockClient
      .query("SELECT pg_advisory_unlock($1)", [AUTO_GENERATE_LOCK_KEY])
      .catch(() => {});
    lockClient.release();
  }
}

async function runAutoGenerate({ simulateToday } = {}) {
  const { rows: facilities } = await pool.query(
    "SELECT DISTINCT facility FROM nurses WHERE facility IS NOT NULL AND is_active = true",
  );
  // Upcoming periods follow each facility's latest activated configuration, so
  // partition staff by its role groups (legacy role-name matching otherwise).
  const groupOf = roleGroupResolver(await activeRoleGroups(pool, "9999-12-31"));

  for (const { facility } of facilities) {
    const { rows: facilityNurses } = await pool.query(
      "SELECT id, name, role, ward, facility, target_hours FROM nurses WHERE facility = $1 AND is_active = true",
      [facility],
    );
    if (!facilityNurses.length) continue;

    const { rows: wards } = await pool.query(
      `SELECT id, name, facility, min_morning_nurses, min_morning_na, min_night_nurses, min_night_na
         FROM wards WHERE facility = $1 OR facility IS NULL`,
      [facility],
    );
    const facilityIds = facilityNurses.map((n) => n.id);

    // Ward-based units — everyone not in a facility-wide role, grouped by their first ward.
    const wardNurses = facilityNurses.filter((n) => !groupOf(n.role, facility));
    const wardNames = [...new Set(wardNurses.map((n) => parseWards(n.ward)[0]).filter(Boolean))];
    for (const wardName of wardNames) {
      await generateUnit({
        facility,
        facilityIds,
        unitNurses: wardNurses.filter((n) => parseWards(n.ward)[0] === wardName),
        wardsForGen: wards.filter((w) => w.name === wardName),
        ward: wardName,
        roleGroup: null,
        simulateToday,
      });
    }

    // Facility-wide role groups.
    for (const key of ["matron", "head", "porter", "intern"]) {
      const groupNurses = facilityNurses.filter((n) => groupOf(n.role, facility) === key);
      if (!groupNurses.length) continue;
      await generateUnit({
        facility,
        facilityIds,
        unitNurses: groupNurses,
        wardsForGen: [],
        ward: null,
        roleGroup: key,
        simulateToday,
      });
    }
  }
}

async function generateUnit({
  facility,
  facilityIds,
  unitNurses,
  wardsForGen,
  ward,
  roleGroup,
  simulateToday,
}) {
  const unitIds = unitNurses.map((n) => n.id);
  const unitLabel = ward ?? roleGroup;

  // Determine this unit's OWN current period, independent of any other
  // unit/facility — a unit can fall behind the rest of the system (e.g. it
  // was reverted by HR after other units already published further ahead),
  // and a single global "next period" would otherwise regenerate over its
  // still-unfinished work or check its deadline against the wrong dates.
  const period =
    (await getUnitPeriod(unitIds, ward)) ??
    (await configuredScheduling.initialAutomaticPeriod(facility));
  if (!period || period.hasActive) return; // never published yet, or already mid-lifecycle for its own period

  const window = await getWindowForPeriod(period.periodStart, { simulateToday });
  if (!window.generateIsDue) return;

  const genStart = period.periodStart;
  const genEnd = period.periodEnd;
  // A paused or failing configured policy must never fall back to legacy rules.
  try {
    const configured = await configuredScheduling.generateAutomaticUnit({
      facilityName: facility,
      startDate: genStart,
      nurseIds: unitIds,
      dryRun: DRY_RUN,
    });
    if (configured) {
      if (configured.written > 0 && !configured.dryRun)
        await notifyUnit(
          facility,
          "rota_autogenerated",
          unitLabel,
          genStart,
          ["head_nurse", "chief_matron", "cno", "admin"],
          [],
        );
      console.log(
        `[auto-generate-rota] ${facility}/${unitLabel}: ${configured.reason ?? (configured.dryRun ? "configured dry run" : `${configured.written} configured cells`)}`,
      );
      return;
    }
  } catch (error) {
    console.error(
      `[auto-generate-rota] Configured generation blocked for ${facility}/${unitLabel}:`,
      error.message,
    );
    return;
  }

  // Pattern-continuity lookback stays facility-wide (matches the manual
  // Generate button's behavior) even though genStart is now unit-specific —
  // only the reference date moved per-unit, not the scope of history used.
  //
  // ORDER BY ... ASC LIMIT 1 is deliberate, not a typo: this needs the
  // EARLIEST shift_date on or before dayBefore — the facility's true
  // scheduling epoch (day 0 of periodOffset) — matching what rota.tsx's
  // manual Generate button gets from GET /shift-assignments?to=...&limit=1
  // (that route's default sort is ascending, see routes/shift-assignments.js).
  // This previously used DESC, which returns the LATEST date instead — in
  // normal operation that's just "yesterday", collapsing periodOffset to a
  // constant 1 on every run regardless of how many periods have actually
  // elapsed. That silently broke the mathematical fallback phase formula in
  // auto-schedule.ts (scheduleGroup/scheduleCoverageNurses), which is only
  // reached when a nurse's recent shift history can't be pattern-matched —
  // producing exactly the intermittent "N shift immediately followed by M"
  // rest-safety violations this was fixed for.
  let periodOffset = 0;
  let previousAssignments = [];
  const dayBefore = addDays(genStart, -1);
  const { rows: epochRows } = await pool.query(
    `SELECT shift_date FROM shift_assignments
      WHERE nurse_id = ANY($1) AND shift_date <= $2
      ORDER BY shift_date ASC LIMIT 1`,
    [facilityIds, dayBefore],
  );
  if (epochRows[0]) {
    periodOffset = daysBetween(epochRows[0].shift_date.slice(0, 10), genStart);
  }
  if (periodOffset > 0) {
    const { rows: prevRows } = await pool.query(
      `SELECT nurse_id, shift_date, shift FROM shift_assignments
        WHERE nurse_id = ANY($1) AND shift_date BETWEEN $2 AND $3`,
      [facilityIds, addDays(genStart, -5), addDays(genStart, -1)],
    );
    previousAssignments = prevRows;
  }

  const { rows: leave } = await pool.query(
    `SELECT nurse_id, from_date::text, to_date::text, status, type FROM leave_requests
      WHERE nurse_id = ANY($1) AND status = 'Approved' AND from_date <= $3 AND to_date >= $2`,
    [unitIds, genStart, genEnd],
  );

  // Defensive backstop — getUnitPeriod()'s hasActive check above should
  // already prevent reaching here with existing rows for this unit/period.
  const { rows: existing } = await pool.query(
    `SELECT 1 FROM shift_assignments
      WHERE nurse_id = ANY($1) AND shift_date BETWEEN $2 AND $3 LIMIT 1`,
    [unitIds, genStart, genEnd],
  );
  if (existing.length) return;

  // Expire any leave request still Pending for this unit's nurses/period. By
  // generation time (T-19) it should already have been decided — rather than
  // block generation indefinitely on someone else's inaction (the old
  // behavior here), resolve it automatically so generation always proceeds
  // using only what's actually Approved (generateSchedule/inLeave already
  // only ever honor 'Approved' rows). Distinct from auto-decline-requests.js's
  // 'Rejected' outcome — this is a system timeout at the generation
  // checkpoint, not a human decision, hence 'Expired' rather than 'Rejected'.
  const { rows: pendingLeaves } = await pool.query(
    `SELECT id, nurse_id, nurse_name, requested_by, type, from_date::text, to_date::text
       FROM leave_requests
      WHERE nurse_id = ANY($1) AND status = 'Pending' AND type != 'Swap'
        AND from_date <= $3 AND to_date >= $2`,
    [unitIds, genStart, genEnd],
  );
  if (pendingLeaves.length) {
    if (DRY_RUN) {
      console.log(
        `[DRY-RUN][auto-generate-rota] would expire ${pendingLeaves.length} pending leave request(s) for ${facility}/${unitLabel}`,
      );
    } else {
      for (const lr of pendingLeaves) {
        await pool.query(
          `UPDATE leave_requests
              SET status = 'Expired', reviewed_at = NOW(),
                  review_note = 'Automatically expired — no decision was made before the rota was generated.'
            WHERE id = $1`,
          [lr.id],
        );
        await pool
          .query(`INSERT INTO audit_logs (actor_name, action, target) VALUES ('system', $1, $2)`, [
            "Leave request auto-expired (rota generation)",
            `${lr.nurse_name} · ${lr.type} · ${lr.from_date} → ${lr.to_date}`,
          ])
          .catch(() => {});
        await notify(lr.requested_by, `leave_expired_${lr.id}`);
        const profileId = await findProfileId(lr.nurse_id, lr.nurse_name);
        if (profileId && profileId !== lr.requested_by) {
          await notify(profileId, `leave_expired_${lr.id}_staff`);
        }
      }
      console.log(
        `[auto-generate-rota] expired ${pendingLeaves.length} pending leave request(s) for ${facility}/${unitLabel}`,
      );
    }
  }

  const { assignments, violations } = generateSchedule({
    nurses: unitNurses,
    wards: wardsForGen,
    leave,
    startDate: new Date(genStart + "T00:00:00"),
    // The whole rota period: a calendar month (or an earlier 28-day period).
    days: daysBetween(genStart, genEnd) + 1,
    facility,
    periodOffset,
    previousAssignments,
  });

  if (DRY_RUN) {
    console.log(
      `[DRY-RUN][auto-generate-rota] would generate ${assignments.length} cell(s) for ${facility}/${unitLabel} (${violations.length} safety violation(s))`,
    );
    return;
  }

  const rows = assignments;
  const client = await pool.connect();
  try {
    await client.query("BEGIN");
    const saved = await persistRotaDraft(client, {
      nurseIds: unitIds,
      startDate: genStart,
      endDate: genEnd,
      assignments: rows,
      actorName: "System (auto-generated)",
      onlyIfEmpty: true,
    });
    if (saved.skipped) {
      await client.query("ROLLBACK");
      return;
    }
    await client.query("COMMIT");
  } catch (error) {
    await client.query("ROLLBACK");
    throw error;
  } finally {
    client.release();
  }

  await pool
    .query(`INSERT INTO audit_logs (actor_name, action, target) VALUES ('system', $1, $2)`, [
      "Rota auto-generated",
      `${facility} · ${unitLabel} · ${genStart} → ${genEnd} (${rows.length} cell(s)${
        violations.length
          ? `, ${violations.length} safety warning(s): ${violationLines(violations).join("; ")}`
          : ""
      })`,
    ])
    .catch(() => {});
  await notifyUnit(
    facility,
    "rota_autogenerated",
    unitLabel,
    genStart,
    ["head_nurse", "chief_matron", "cno", "admin"],
    violations,
  );
}

// Resolve a nurse to their login profile — mirrors the same fallback chain
// used in jobs/auto-decline-requests.js (profile_id link, then name match).
async function findProfileId(nurseId, nurseName) {
  const { rows } = await pool.query(
    `SELECT COALESCE(
       (SELECT p.id FROM nurses n JOIN profiles p ON p.id = n.profile_id WHERE n.id = $1),
       (SELECT p.id FROM nurses n JOIN profiles p ON LOWER(p.full_name) = LOWER(n.name) WHERE n.id = $1 LIMIT 1),
       (SELECT p.id FROM profiles p WHERE $2::text IS NOT NULL AND LOWER(p.full_name) = LOWER($2) LIMIT 1)
     ) AS profile_id`,
    [nurseId, nurseName],
  );
  return rows[0]?.profile_id ?? null;
}

async function notify(userId, notifKey) {
  if (!userId) return;
  await pool
    .query(
      `INSERT INTO notification_state (user_id, notif_key, is_read)
       VALUES ($1, $2, false)
       ON CONFLICT (user_id, notif_key) DO NOTHING`,
      [userId, notifKey],
    )
    .catch(() => {});
}

async function notifyUnit(facility, prefix, unitLabel, periodStart, roles, violations) {
  const facilitySlug = facility.toLowerCase().replace(/\s+/g, "_");
  const unitSlug = String(unitLabel).toLowerCase().replace(/\s+/g, "_");
  // "|" separates the payload segments (facility/unit/period) so the bell can
  // parse them back out unambiguously — a plain "_" join can't be split
  // reliably since facility and ward names can themselves contain "_".
  const notifKey = `${prefix}_${facilitySlug}|${unitSlug}|${periodStart}`;
  const { rows } = await pool.query(
    `SELECT DISTINCT p.id, p.email FROM profiles p
       JOIN user_roles ur ON ur.user_id = p.id
      WHERE ur.role = ANY($1) AND p.is_active = true`,
    [roles],
  );
  const copy = EMAIL_COPY[prefix]?.(facility, unitLabel, periodStart, violations);
  for (const { id, email } of rows) {
    // Generation only ever runs once per unit/period (guarded by the
    // NOT EXISTS-equivalent `existing` check in generateUnit above), so this
    // notifKey should only ever be seen once anyway — but dedupe on
    // "was this row just inserted" the same way auto-submit-draft.js /
    // auto-publish-rota.js do, so a retry or manual re-run never re-sends.
    const { rows: upserted } = await pool
      .query(
        `INSERT INTO notification_state (user_id, notif_key, is_read)
         VALUES ($1, $2, false)
         ON CONFLICT (user_id, notif_key) DO UPDATE SET is_read = false, updated_at = NOW()
         RETURNING (xmax = 0) AS is_new`,
        [id, notifKey],
      )
      .catch(() => ({ rows: [{ is_new: false }] }));

    if (copy && upserted[0]?.is_new) {
      sendMail({
        to: email,
        subject: copy.subject,
        title: copy.subject,
        bodyHtml: copy.bodyHtml,
        ctaText: "Open Rota",
        ctaUrl: portalUrl(copy.ctaPath),
      }).catch(() => {});
    }
  }
}

function startAutoGenerateJob() {
  // Every run happens once per hospital, inside that hospital's data context.
  const tick = () =>
    forEachHospital(pool, () => autoGenerateRota()).catch((err) =>
      console.error("[auto-generate-rota] hospital loop failed:", err.message),
    );
  tick();
  cron.schedule("*/5 * * * *", tick);
  console.log("[auto-generate-rota] Auto-generate rota job started (runs every 5 minutes)");
}

module.exports = { startAutoGenerateJob, runAutoGenerate };
